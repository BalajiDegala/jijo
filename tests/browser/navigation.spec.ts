import { expect, test } from '@playwright/test';
import axe from 'axe-core';

test('the module directory leads to a scoped workspace and the sidebar gives the canvas its space back', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 860 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Learning modules' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Resource playground' })).toHaveCount(0);
  await expect(page.getByRole('link', { name: /Networking/ })).toHaveAttribute('href', 'https://roopa-net.vercel.app');
  await page.addScriptTag({ content: axe.source });
  const findings = await page.evaluate(async () => (await window.axe.run(document, { runOnly: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'] })).violations.map(issue => issue.id));
  expect(findings).toEqual([]);
  await page.screenshot({ path: 'test-results/module-directory.png' });
  await page.getByRole('link', { name: /Docker.*Open module/ }).click();
  const sidebar = page.getByRole('navigation', { name: 'Docker module' });
  await expect(sidebar.getByRole('link', { name: 'Resource playground' })).toBeHidden();
  await sidebar.getByText('Playgrounds', { exact: true }).click();
  await sidebar.getByRole('link', { name: 'Resource playground' }).click();
  await expect(page).toHaveTitle('Resource playground · JIJO Learning Studio');
  await expect(sidebar).toBeHidden();
  const canvas = page.locator('.pg-canvas');
  await expect(canvas).toBeVisible();
  const wide = (await canvas.boundingBox())!.width;
  await page.getByRole('button', { name: 'Open sidebar' }).click();
  await expect(sidebar.getByRole('link', { name: 'Resource playground' })).toHaveAttribute('aria-current', 'page');
  await expect(sidebar.getByRole('link', { name: 'Field notes' })).toBeHidden();
  const narrow = (await canvas.boundingBox())!.width;
  expect(wide - narrow).toBeGreaterThan(150);
  await page.reload();
  await expect(sidebar).toBeVisible();
  await page.getByRole('button', { name: 'Close sidebar' }).click();
  await page.goto('/#lab');
  await expect(sidebar).toBeHidden();
  await page.getByRole('link', { name: 'Modules', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Learning modules' })).toBeFocused();
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'The unreachable container' })).toBeVisible();
});

test('mobile module navigation can be dismissed with Escape and closes after a selection', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto('/');
  await page.getByRole('link', { name: /Docker.*Open module/ }).click();
  const menu = page.getByRole('button', { name: 'Toggle navigation' });
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await menu.click();
  await expect(page.getByRole('link', { name: 'All modules' })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(menu).toBeFocused();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await menu.click();
  const sidebar = page.getByRole('navigation', { name: 'Docker module' });
  await sidebar.getByText('Playgrounds', { exact: true }).click();
  await sidebar.getByRole('link', { name: 'Dockerfile playground' }).click();
  await expect(page.getByRole('heading', { name: 'Dockerfile playground' })).toBeFocused();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await expect(page.getByLabel('Dockerfile editor')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
