export function nextScenarioId(id) {
  const path = learningPaths.find((p) => p.ids.includes(id));
  const ordered = Object.keys(scenarioConcepts);
  return (
    path?.ids[path.ids.indexOf(id) + 1] ||
    ordered[(ordered.indexOf(id) + 1) % ordered.length]
  );
}
