import type { Resource, Rule, Topology } from "../engine/types";

export const allowAll = (): Rule[] =>
  ["inbound", "outbound"].map((direction, i) => ({
    id: `allow-${direction}`,
    direction: direction as Rule["direction"],
    protocol: "ALL",
    fromPort: 0,
    toPort: 65535,
    cidr: "0.0.0.0/0",
    action: "allow",
    priority: 100 + i,
  }));
export function localTemplate(routed = false): Topology {
  const resources: Resource[] = [
    {
      id: "pc1",
      kind: "computer",
      name: "Workstation",
      x: 80,
      y: 200,
      ip: "192.168.1.10",
      prefix: 24,
      gateway: routed ? "192.168.1.1" : "",
      mac: "02:00:00:00:00:10",
      enabled: true,
      services: [80, 443],
    },
    {
      id: "sw1",
      kind: "switch",
      name: "Access switch",
      x: 370,
      y: 200,
      enabled: true,
    },
    {
      id: "pc2",
      kind: "server",
      name: "Linux server",
      x: routed ? 950 : 670,
      y: 200,
      ip: routed ? "192.168.2.10" : "192.168.1.20",
      prefix: 24,
      gateway: routed ? "192.168.2.1" : "",
      mac: "02:00:00:00:00:20",
      enabled: true,
      services: [53, 80, 443],
    },
  ];
  const links = [
    { id: "c1", source: "pc1", target: "sw1" },
    { id: "c2", source: "sw1", target: routed ? "r1" : "pc2" },
  ];
  if (routed) {
    resources.push({
      id: "r1",
      kind: "router",
      name: "Edge router",
      x: 660,
      y: 200,
      enabled: true,
      forwarding: true,
      interfaces: [
        { id: "eth0", ip: "192.168.1.1", prefix: 24 },
        { id: "eth1", ip: "192.168.2.1", prefix: 24 },
      ],
      routes: [],
    });
    links.push({ id: "c3", source: "r1", target: "pc2" });
  }
  return {
    version: 1,
    name: routed ? "Across two networks" : "My first network",
    mode: "local",
    resources,
    links,
    dns: { "server.netverse": resources[2].ip! },
  };
}
export function emptyTemplate(mode: "local" | "aws"): Topology {
  return {
    version: 1,
    name: "Untitled network",
    mode,
    resources: [],
    links: [],
    dns: { "example.net": "8.8.8.8" },
  };
}

